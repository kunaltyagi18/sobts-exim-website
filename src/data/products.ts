const category = (slug: ProductCategory) => productCategories.find((item) => item.slug === slug)!;

type CatalogueProductInput = Omit<Product, "categoryLabel" | "image" | "alt"> & {
  image?: string;
  alt?: string;
};

const catalogueProduct = (item: CatalogueProductInput): Product => {
  const productCategory = category(item.category);
  return {
    ...item,
    categoryLabel: productCategory.name,
    image: item.image ?? productCategory.image,
    alt: item.alt ?? productCategory.alt,
  };
};

